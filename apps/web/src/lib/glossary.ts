// 简单辅助:用术语查 GLOSS,查不到返回 null
export function gloss(term: string): Gloss | null {
  // 直接匹配
  if (GLOSS[term]) return GLOSS[term];
  // 兼容"日主 丙火"这种带后缀:截前 2 字
  for (const k of Object.keys(GLOSS)) {
    if (term.startsWith(k)) return GLOSS[k];
  }
  return null;
}
