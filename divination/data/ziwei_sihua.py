def judge_palace_sihua(palace_name: str, hua_counts: dict[str, int]) -> dict:
    """根据宫位 + 四化触发数,给出简要判断。

    简化规则:
        - 化禄 ≥ 2: 大吉（主财源滚滚）
        - 化忌 ≥ 2: 大凶（多阻碍）
        - 化禄 + 化忌: 凶中带吉（先好后坏）
        - 化禄 + 化权: 大吉（名利双收）
        - 化科 + 化权: 大吉（名权双收）
        - 化忌单: 平常,有阻但不凶
        - 无四化: 平常
    """
    luck: str
    meaning: str

    lu = hua_counts.get("禄", 0)
    quan = hua_counts.get("权", 0)
    ke = hua_counts.get("科", 0)
    ji = hua_counts.get("忌", 0)

    if lu >= 2 and ji == 0:
        luck = "大吉"
        meaning = f"{palace_name}化禄多,主{_palace_lu_meaning(palace_name)},大吉。"
    elif ji >= 2 and lu == 0:
        luck = "大凶"
        meaning = f"{palace_name}化忌多,主{_palace_ji_meaning(palace_name)},须防。"
    elif lu >= 1 and ji >= 1:
        luck = "凶中带吉"
        meaning = f"{palace_name}化禄化忌同宫,主先好后坏,须谨慎。"
    elif lu >= 1 and quan >= 1:
        luck = "吉"
        meaning = f"{palace_name}化禄化权,主{_palace_lu_meaning(palace_name)},名利双收。"
    elif ke >= 1 and quan >= 1:
        luck = "吉"
        meaning = f"{palace_name}化科化权,主名声与权柄兼具,大吉。"
    elif lu >= 1:
        luck = "吉"
        meaning = f"{palace_name}化禄,主{_palace_lu_meaning(palace_name)},小吉。"
    elif ji >= 1:
        luck = "小凶"
        meaning = f"{palace_name}化忌,主{_palace_ji_meaning(palace_name)},有阻。"
    elif quan >= 1 or ke >= 1:
        luck = "平"
        meaning = f"{palace_name}化权/科,主掌权/有名,平常。"
    else:
        luck = "平"
        meaning = f"{palace_name}无四化,主平常。"

    return {
        "palace": palace_name,
        "hua_counts": hua_counts,
        "luck": luck,
        "meaning": meaning,
    }


