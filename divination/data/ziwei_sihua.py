# 4. 四化查询与统计
# ══════════════════════════════════════════════════════════════
def get_natal_sihua(year_gan: str) -> dict[str, str]:
    """根据生年天干,返回该年出生者的四化星曜。"""
    return NATAL_SIHUA.get(year_gan, {})


def get_sihua_meaning(hua_type: str, star: str) -> str:
    """返回某化星的具体含义。"""
    hua_data = SIHUA_MEANINGS.get(hua_type, {})
    elements = hua_data.get("elements", {})
    return elements.get(star, f"{hua_type}{star}")


def get_star_sihua_in_year(year_gan: str, star: str) -> str | None:
    """查询某星在某年生年四化中是哪一化（如 甲年破军化权）。

    Returns: '禄'/'权'/'科'/'忌' 或 None（不在四化表中）
    """
    nat = get_natal_sihua(year_gan)
    for hua, s in nat.items():
        if s == star:
            return hua
    return None


def get_stars_with_sihua(hua_type: str) -> list[str]:
    """返回 10 天干中触发某化（如'禄'）的全部星曜。"""
    return [nat[hua_type] for nat in NATAL_SIHUA.values() if hua_type in nat]


def get_palace_sihua_count(palace_stars: list[str], year_gan: str) -> dict[str, int]:
    """统计某宫位主星在某年出生者的四化触发情况。

    Args:
        palace_stars: 该宫位所有主星列表
        year_gan: 出生年天干

    Returns:
        {禄: n, 权: n, 科: n, 忌: n} 各化触发次数
    """
    nat = get_natal_sihua(year_gan)
    counts = {"禄": 0, "权": 0, "科": 0, "忌": 0}
    for star in palace_stars:
        for hua, s in nat.items():
            if s == star:
                counts[hua] += 1
    return counts


