def get_tarot_system(key: str) -> TarotSystemInfo | None:
    """查询塔罗系统."""
    return TAROT_SYSTEMS.get(key)


def get_tarot_system_names() -> list[str]:
    """返回所有塔罗系统名."""
    return list(TAROT_SYSTEMS.keys())


def search_guanyin_qian(index: int) -> QianDraw | None:
    """按序号查询观音灵签."""
    for q in GUANYIN_QIAN:
        if q.index == index:
            return q
    return None


def search_guandi_qian(index: int) -> QianDraw | None:
    """按序号查询关帝灵签."""
    for q in GUANDI_QIAN:
        if q.index == index:
            return q
    return None


def get_qian_by_category(qian_list: list[QianDraw], category: str) -> list[QianDraw]:
    """按分类筛选签文."""
    return [q for q in qian_list if q.category == category]


def get_qiantong_by_material(material_keyword: str) -> list[QianTongSpec]:
    """按材料关键词筛选签筒."""
    return [q for q in QIANTONG_SPECS if material_keyword in q.material]


def get_luban_lucky_segments() -> list[dict[str, str | int]]:
    """返回鲁班尺常用吉数."""
    return list(LUBAN_LUCKY_MM)


def get_luban_segment_for_mm(mm: int) -> LubanSegment | None:
    """按毫米查找鲁班尺段位."""
    # 归一到第一或第二尺
    mm = mm % 429
    if mm == 0:
        mm = 429
    for seg in LUBAN_SEGMENTS:
        if seg.range_mm[0] <= mm <= seg.range_mm[1]:
            return seg
    return None


def get_ritual_tools_by_category(category: str) -> list[RitualTool]:
    """按分类筛选法器."""
