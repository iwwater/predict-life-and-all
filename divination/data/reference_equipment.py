# 补足至 100 签 (批量生成剩余 75 签, 各分类均匀分布)
def _fill_qian_to_100(base: list[QianDraw]) -> list[QianDraw]:
    """补全至 100 签, 分配各分类."""
    cats_cycle = ["上上", "上", "中", "下", "下下"]
    result = list(base)
    for i in range(len(base) + 1, 101):
        cat = cats_cycle[(i - 1) % 5]
        result.append(QianDraw(
            i, f"观音第{i}签", cat,
            f"签文第{i}则 · 待校订",
            f"{'大吉大利, 万事如意' if cat == '上上' else '顺其自然, 水到渠成' if cat == '上' else '平平淡淡, 不争不抢' if cat == '中' else '谨慎行事, 守成为上' if cat == '下' else '退守待时, 莫强出头'}",
        ))
    return result

