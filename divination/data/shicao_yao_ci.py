# 4. 构建查询字典
# ══════════════════════════════════════════════════════════════
def _build_all_yao_ci() -> dict[tuple[str, int, bool], ChangedYaoCi]:
    """将原始数据转为 ChangedYaoCi 字典。"""
    result: dict[tuple[str, int, bool], ChangedYaoCi] = {}
    for name, line_num, is_yang_old, yao_ci, xiang_ci, interp in _RAW_YAO_CI:
        num = _HEXAGRAM_NUM.get(name, 0)
        entry = ChangedYaoCi(
            hexagram_num=num,
            hexagram_name=name,
            line_num=line_num,
            is_yang_old=is_yang_old,
            yao_ci=yao_ci,
            xiang_ci=xiang_ci,
            interpretation=interp,
            source="《周易》",
        )
        result[(name, line_num, is_yang_old)] = entry
    return result


SHICAO_YAO_CI: dict[tuple[str, int, bool], ChangedYaoCi] = _build_all_yao_ci()


def _count_complete() -> int:
    """统计完整录入的条目数 (含 interpretation 非空)。"""
    return sum(1 for e in SHICAO_YAO_CI.values() if e.interpretation)


_COMPLETE_COUNT: int = _count_complete()


# ══════════════════════════════════════════════════════════════
# 5. 查询函数
# ══════════════════════════════════════════════════════════════
def lookup_changed_yao_ci(
    hexagram_name: str,
    line_num: int,
    is_yang_old: bool,
) -> ChangedYaoCi | None:
    """查询指定卦、爻位、变化类型的变爻辞。

    Args:
        hexagram_name: 卦名 (如 "乾", "坤")
        line_num: 爻位 (1-6)
        is_yang_old: True=老阳(9)→变阴, False=老阴(6)→变阳

    Returns:
        ChangedYaoCi 或 None
    """
    key = (hexagram_name, line_num, is_yang_old)
    return SHICAO_YAO_CI.get(key)


def lookup_by_hexagram(hexagram_name: str) -> list[ChangedYaoCi]:
    """查询某卦所有变爻辞条目。"""
    return [
        e for (name, _, _), e in SHICAO_YAO_CI.items()
        if name == hexagram_name
    ]


def get_all_entries() -> dict[tuple[str, int, bool], ChangedYaoCi]:
    """返回全部变爻辞数据。"""
    return dict(SHICAO_YAO_CI)


def get_complete_count() -> int:
    """返回完整录入的条目数。"""
    return _COMPLETE_COUNT


def get_total_entries() -> int:
    """返回全部条目数。"""
    return len(SHICAO_YAO_CI)
